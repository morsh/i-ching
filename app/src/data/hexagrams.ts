/**
 * All 64 hexagrams sorted by King Wen number (1–64).
 */
export const HEXAGRAMS: readonly Hexagram[] = Object.freeze(
  _DATA.slice().sort((a, b) => a.number - b.number)
);

/**
 * O(1) lookup by 6-character binary string (bottom-line-first).
 */
export const HEXAGRAM_BY_BINARY: ReadonlyMap<string, Hexagram> = new Map(
  HEXAGRAMS.map(h => [h.binary, h])
);

/**
 * Looks up a hexagram by its 6-character binary code (bottom-to-top).
 *
 * @param binary A 6-character string of `'0'`/`'1'`, index 0 = bottom line.
 * @returns The matching {@link Hexagram}.
 * @throws {Error} If no hexagram with that binary exists.
 */
export function getHexagramByBinary(binary: string): Hexagram {
  const h = HEXAGRAM_BY_BINARY.get(binary);
  if (!h) throw new Error(`Unknown hexagram binary: "${binary}"`);
  return h;
}

/**
 * Looks up a hexagram by its King Wen number.
 *
 * @param n King Wen number, 1..64.
 * @returns The matching {@link Hexagram}.
 * @throws {Error} If no hexagram with number `n` exists.
 */
export function getHexagramByNumber(n: number): Hexagram {
  const h = HEXAGRAMS.find(h => h.number === n);
  if (!h) throw new Error(`Unknown hexagram number: ${n}`);
  return h;
}
